#include "openscadgenerator.h"
#include "scenestringutils.h"

#include <QColor>
#include <QStringList>

void OpenScadGenerator::appendShape(QString *code, const ShapeNode &shape, const QString &indent)
{
    const QString shapeCode = shapeToOpenScad(shape);
    const QStringList lines = shapeCode.split('\n');

    for (const QString &line : lines) {
        if (!line.trimmed().isEmpty())
            *code += indent + line + "\n";
    }
}

QString OpenScadGenerator::generate(const SceneDocument &scene)
{
    return generateWithSourceMap(scene, nullptr);
}

QString OpenScadGenerator::generateWithSourceMap(const SceneDocument &scene, QVector<SourceRange> *ranges)
{
    QString code;
    if (ranges)
        ranges->clear();

    code += "// Generated by OpenSCAD Visual Editor Prototype\n";
    code += "// UI -> OpenSCAD code\n\n";

    appendSceneModule(&code, scene, ranges);
    return code;
}

static QString treeOperationName(SceneDocument::TreeNode::Operation operation)
{
    if (operation == SceneDocument::TreeNode::Difference)
        return "difference";
    if (operation == SceneDocument::TreeNode::Intersection)
        return "intersection";
    if (operation == SceneDocument::TreeNode::Hull)
        return "hull";
    if (operation == SceneDocument::TreeNode::Minkowski)
        return "minkowski";
    return "union";
}

static QString colorLiteral(const QColor &color)
{
    return QStringLiteral("\"#%1%2%3\"")
        .arg(color.red(), 2, 16, QLatin1Char('0'))
        .arg(color.green(), 2, 16, QLatin1Char('0'))
        .arg(color.blue(), 2, 16, QLatin1Char('0'));
}

static QStringList moduleParameterArgs(const SceneDocument::TreeNode &moduleNode)
{
    QStringList args;
    for (const SceneDocument::TreeNode &child : moduleNode.children) {
        if (child.type == SceneDocument::TreeNode::Variable && child.isParameter) {
            const QString expr = child.variableExpression.trimmed().isEmpty()
                                     ? QString::number(child.variableValue)
                                     : child.variableExpression.trimmed();
            args.append(QString("%1 = %2").arg(child.variableName, expr));
        }
    }
    return args;
}

// Return the module signature string "name(p1=e1, p2=e2)".
static QString moduleSignature(const SceneDocument::TreeNode &moduleNode)
{
    const QStringList params = moduleParameterArgs(moduleNode);
    const QString name = moduleNode.moduleName.trimmed().isEmpty()
                             ? QStringLiteral("scene_model")
                             : moduleNode.moduleName.trimmed();
    return params.isEmpty() ? name + "()" : name + "(" + params.join(", ") + ")";
}

// Return the call statement "name(p1=v1, p2=v2);\n" using current parameter values.
static QString moduleCallStatement(const SceneDocument::TreeNode &moduleNode)
{
    const QString name = moduleNode.moduleName.trimmed().isEmpty()
                             ? QStringLiteral("scene_model")
                             : moduleNode.moduleName.trimmed();
    const QStringList args = moduleNode.moduleCallArguments.trimmed().isEmpty()
                                 ? QStringList()
                                 : splitAtTopLevelCommas(moduleNode.moduleCallArguments);
    return args.isEmpty() ? name + "();\n" : name + "(" + args.join(", ") + ");\n";
}

static QString moduleCallStatement(const SceneDocument::TreeNode &moduleNode,
                                   const SceneDocument::TreeNode &callNode)
{
    SceneDocument::TreeNode call = moduleNode;
    call.moduleCallArguments = callNode.moduleCallArguments;
    return moduleCallStatement(call);
}

void OpenScadGenerator::appendSceneModule(QString *code, const SceneDocument &scene, QVector<SourceRange> *ranges)
{
    // Collect children, flattening the Scene container inline at root level.
    // Scene children (vars, primitives, ModuleCalls) are treated as if they were at root.
    QVector<const SceneDocument::TreeNode *> globalVars;
    QVector<const SceneDocument::TreeNode *> bodyChildren;
    QVector<const SceneDocument::TreeNode *> moduleChildren;
    QVector<const SceneDocument::TreeNode *> moduleCalls;

    auto categorize = [&](const SceneDocument::TreeNode &child) {
        if (child.type == SceneDocument::TreeNode::Variable)
            globalVars.append(&child);
        else if (child.type == SceneDocument::TreeNode::ModuleCall)
            moduleCalls.append(&child);
        else if (child.type == SceneDocument::TreeNode::Group
                 && child.operation == SceneDocument::TreeNode::Module)
            moduleChildren.append(&child);
        else
            bodyChildren.append(&child);
    };

    for (const SceneDocument::TreeNode &child : scene.treeRoot().children) {
        if (child.type == SceneDocument::TreeNode::Group
            && child.operation == SceneDocument::TreeNode::Scene) {
            for (const SceneDocument::TreeNode &sceneChild : child.children)
                categorize(sceneChild);
        } else {
            categorize(child);
        }
    }

    // --- 1. Emit global variables ---
    for (const SceneDocument::TreeNode *var : globalVars) {
        const int start = code->size();
        const QString expr = var->variableExpression.trimmed().isEmpty()
                                 ? QString::number(var->variableValue)
                                 : var->variableExpression.trimmed();
        *code += QString("%1 = %2;\n").arg(var->variableName, expr);
        if (ranges)
            ranges->append({var->id, start, code->size() - start});
    }

    // --- 2. Emit named module definitions ---
    for (const SceneDocument::TreeNode *mod : moduleChildren) {
        *code += "\n";
        const int moduleStart = code->size();
        *code += QString("module %1 {\n").arg(moduleSignature(*mod));
        for (const SceneDocument::TreeNode &child : mod->children) {
            if (child.type == SceneDocument::TreeNode::Variable && child.isParameter)
                continue;
            appendTreeNode(code, child, scene, "    ", ranges);
        }
        *code += "}\n";
        if (ranges)
            ranges->append({mod->id, moduleStart, code->size() - moduleStart});
    }

    // --- 3. Emit body children directly at top level ---
    if (!bodyChildren.isEmpty()) {
        *code += "\n";
        const int bodyStart = code->size();
        for (const SceneDocument::TreeNode *child : bodyChildren)
            appendTreeNode(code, *child, scene, "", ranges);
        if (ranges)
            ranges->append({scene.treeRoot().id, bodyStart, code->size() - bodyStart});
    } else if (moduleChildren.isEmpty() && globalVars.isEmpty()) {
        *code += "\n// Add shapes from the tree editor.\n";
    }

    // --- 4. Module calls from explicit ModuleCall nodes in Scene ---
    if (!moduleCalls.isEmpty()) {
        *code += "\n";
        for (const SceneDocument::TreeNode *call : moduleCalls) {
            const int start = code->size();
            // Look up the referenced module group to get correct parameter values.
            const SceneDocument::TreeNode *modGroup = scene.treeNodeById(call->shapeId);
            if (modGroup && modGroup->type == SceneDocument::TreeNode::Group
                && modGroup->operation == SceneDocument::TreeNode::Module) {
                *code += moduleCallStatement(*modGroup, *call);
            } else {
                *code += call->moduleName + "();\n";
            }
            if (ranges)
                ranges->append({call->id, start, code->size() - start});
        }
    }
}

void OpenScadGenerator::appendTreeNode(QString *code,
                                       const SceneDocument::TreeNode &node,
                                       const SceneDocument &scene,
                                       const QString &indent,
                                       QVector<SourceRange> *ranges)
{
    const int start = code->size();

    if (node.type == SceneDocument::TreeNode::Primitive) {
        if (const ShapeNode *shape = scene.shapeById(node.shapeId)) {
            appendShape(code, *shape, indent);
            if (ranges)
                ranges->append({node.id, start, code->size() - start});
        }
        return;
    }

    if (node.type == SceneDocument::TreeNode::Variable) {
        *code += QString("%1%2 = %3;\n")
                     .arg(indent, node.variableName)
                     .arg(node.variableExpression.trimmed().isEmpty()
                              ? QString::number(node.variableValue)
                              : node.variableExpression.trimmed());
        if (ranges)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    if (node.type == SceneDocument::TreeNode::ModuleCall) {
        const SceneDocument::TreeNode *modGroup = scene.treeNodeById(node.shapeId);
        if (modGroup && modGroup->type == SceneDocument::TreeNode::Group
            && modGroup->operation == SceneDocument::TreeNode::Module) {
            *code += indent + moduleCallStatement(*modGroup, node);
        } else {
            *code += indent + node.moduleName + "();\n";
        }
        if (ranges)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    // Scene / Module nodes are emitted at the top level by appendSceneModule;
    // if either appears nested (shouldn't happen), flatten children inline.
    if (node.operation == SceneDocument::TreeNode::Scene
        || node.operation == SceneDocument::TreeNode::Module) {
        for (const SceneDocument::TreeNode &child : node.children)
            appendTreeNode(code, child, scene, indent, ranges);
        if (ranges && code->size() > start)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    if (node.operation == SceneDocument::TreeNode::For) {
        const QString variableName = node.loopVariable.trimmed().isEmpty()
                                         ? QStringLiteral("i")
                                         : node.loopVariable.trimmed();
        const QString rangeExpression = node.loopRangeExpression.trimmed().isEmpty()
                                            ? QStringLiteral("[0 : 1 : 3]")
                                            : node.loopRangeExpression.trimmed();
        *code += QString("%1for (%2 = %3) {\n").arg(indent, variableName, rangeExpression);

        for (const SceneDocument::TreeNode &child : node.children)
            appendTreeNode(code, child, scene, indent + "    ", ranges);

        *code += indent + "}\n";
        if (ranges)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    if (node.operation == SceneDocument::TreeNode::Translate
        || node.operation == SceneDocument::TreeNode::Rotate
        || node.operation == SceneDocument::TreeNode::Scale
        || node.operation == SceneDocument::TreeNode::Mirror) {
        QString transformName = QStringLiteral("scale");
        QVector3D transformVector = node.scale;
        if (node.operation == SceneDocument::TreeNode::Translate) {
            transformName = QStringLiteral("translate");
            transformVector = node.position;
        } else if (node.operation == SceneDocument::TreeNode::Rotate) {
            transformName = QStringLiteral("rotate");
            transformVector = node.rotation;
        } else if (node.operation == SceneDocument::TreeNode::Mirror) {
            transformName = QStringLiteral("mirror");
            transformVector = node.position;
        }
        auto txExpr = [&](int axis, float numericValue) -> QString {
            if (axis < node.transformExpressions.size() && !node.transformExpressions[axis].isEmpty())
                return node.transformExpressions[axis];
            return QString::number(numericValue, 'g');
        };
        *code += QString("%1%2([%3, %4, %5]) {\n")
                     .arg(indent, transformName)
                     .arg(txExpr(0, transformVector.x()),
                          txExpr(1, transformVector.y()),
                          txExpr(2, transformVector.z()));

        for (const SceneDocument::TreeNode &child : node.children)
            appendTreeNode(code, child, scene, indent + "    ", ranges);

        *code += indent + "}\n";
        if (ranges)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    if (node.operation == SceneDocument::TreeNode::Color) {
        *code += QString("%1color(%2) {\n").arg(indent, colorLiteral(node.color));

        for (const SceneDocument::TreeNode &child : node.children)
            appendTreeNode(code, child, scene, indent + "    ", ranges);

        *code += indent + "}\n";
        if (ranges)
            ranges->append({node.id, start, code->size() - start});
        return;
    }

    appendTreeGroup(code, treeOperationName(node.operation), node, scene, indent, ranges);
    if (ranges)
        ranges->append({node.id, start, code->size() - start});
}

void OpenScadGenerator::appendTreeGroup(QString *code,
                                        const QString &name,
                                        const SceneDocument::TreeNode &node,
                                        const SceneDocument &scene,
                                        const QString &indent,
                                        QVector<SourceRange> *ranges)
{
    *code += QString("%1%2() {\n").arg(indent, name);

    for (const SceneDocument::TreeNode &child : node.children)
        appendTreeNode(code, child, scene, indent + "    ", ranges);

    *code += indent + "}\n";
}

QString OpenScadGenerator::shapeToOpenScad(const ShapeNode &shape)
{
    auto paramExpr = [&](int idx, qreal numericValue) -> QString {
        if (idx < shape.parameterExpressions.size() && !shape.parameterExpressions[idx].isEmpty())
            return shape.parameterExpressions[idx];
        return QString::number(numericValue, 'g');
    };

    if (shape.type == ShapeNode::Cube) {
        return QString("cube([%1, %2, %3], center=true);\n")
            .arg(paramExpr(0, shape.size.x()))
            .arg(paramExpr(1, shape.size.y()))
            .arg(paramExpr(2, shape.size.z()));
    }
    if (shape.type == ShapeNode::Sphere) {
        return QString("sphere(r=%1);\n")
            .arg(paramExpr(0, shape.radius));
    }
    if (shape.type == ShapeNode::Cylinder) {
        // parameterExpressions: index 0 = R (radius), index 1 = H (height)
        return QString("cylinder(h=%1, r=%2, center=true);\n")
            .arg(paramExpr(1, shape.height))
            .arg(paramExpr(0, shape.radius));
    }
    if (shape.type == ShapeNode::Cone) {
        // parameterExpressions: index 0 = R1 (bottom), index 1 = R2 (top), index 2 = H
        return QString("cylinder(h=%1, r1=%2, r2=%3, center=true);\n")
            .arg(paramExpr(2, shape.height))
            .arg(paramExpr(0, shape.radius))
            .arg(paramExpr(1, shape.radius2));
    }
    return QString();
}
