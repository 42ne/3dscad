#include "openscadgenerator.h"

#include <QStringList>

void OpenScadGenerator::appendShape(QString *code, const ShapeNode &shape, const QString &indent)
{
    const QString shapeCode = shapeToOpenScad(shape);
    const QStringList lines = shapeCode.split('\n');

    for (const QString &line : lines) {
        if (!line.trimmed().isEmpty())
            *code += indent + line + "\n";
    }
}

QString OpenScadGenerator::generate(const SceneDocument &scene)
{
    QString code;

    code += "// Generated by OpenSCAD Visual Editor Prototype\n";
    code += "// UI -> OpenSCAD code\n\n";

    if (scene.isEmpty()) {
        code += "// Add shapes from the left panel.\n";
        return code;
    }

    const SceneBooleanNode root = buildSceneBooleanTree(scene.shapes());
    appendBooleanNode(&code, root, scene, "");
    return code;
}

void OpenScadGenerator::appendBooleanNode(QString *code, const SceneBooleanNode &node, const SceneDocument &scene, const QString &indent)
{
    switch (node.type) {
    case SceneBooleanNode::Primitive:
        if (const ShapeNode *shape = scene.shapeAt(node.shapeIndex))
            appendShape(code, *shape, indent);
        break;
    case SceneBooleanNode::Union:
        appendBooleanGroup(code, "union", node, scene, indent);
        break;
    case SceneBooleanNode::Difference:
        appendBooleanGroup(code, "difference", node, scene, indent);
        break;
    case SceneBooleanNode::Intersection:
        appendBooleanGroup(code, "intersection", node, scene, indent);
        break;
    case SceneBooleanNode::Empty:
        break;
    }
}

void OpenScadGenerator::appendBooleanGroup(QString *code,
                                           const QString &name,
                                           const SceneBooleanNode &node,
                                           const SceneDocument &scene,
                                           const QString &indent)
{
    *code += QString("%1%2() {\n").arg(indent, name);

    for (const SceneBooleanNode &child : node.children)
        appendBooleanNode(code, child, scene, indent + "    ");

    *code += indent + "}\n";
}

QString OpenScadGenerator::shapeToOpenScad(const ShapeNode &shape)
{
    QString code;

    code += QString("translate([%1, %2, %3])\n")
                .arg(shape.position.x())
                .arg(shape.position.y())
                .arg(shape.position.z());

    code += QString("rotate([%1, %2, %3])\n")
                .arg(shape.rotation.x())
                .arg(shape.rotation.y())
                .arg(shape.rotation.z());

    if (shape.type == ShapeNode::Cube) {
        code += QString("cube([%1, %2, %3], center=true);\n")
                    .arg(shape.size.x())
                    .arg(shape.size.y())
                    .arg(shape.size.z());
    } else if (shape.type == ShapeNode::Sphere) {
        code += QString("sphere(r=%1);\n")
                    .arg(shape.radius);
    } else if (shape.type == ShapeNode::Cylinder) {
        code += QString("cylinder(h=%1, r=%2, center=true);\n")
                    .arg(shape.height)
                    .arg(shape.radius);
    }

    return code;
}
